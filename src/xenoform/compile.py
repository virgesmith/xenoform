logger = get_logger()

_module_registry: dict[str, ModuleSpec] = defaultdict(ModuleSpec)

_load_lock = threading.Lock()

_LOG_TAIL_LINES = 30

_SETUP_PY = """\
# generated by xenoform. To rebuild by hand, from this directory: python setup.py build_ext --inplace
from pybind11.setup_helpers import Pybind11Extension, build_ext
from setuptools import setup

setup(
    name={ext_name!r},
    ext_modules=[
        Pybind11Extension(
            {module_name!r},
            ["module.cpp"],
            define_macros={define_macros!r},
            extra_compile_args={extra_compile_args!r},
            extra_link_args={extra_link_args!r},
            include_dirs={include_dirs!r},
            cxx_std={cxx_std!r},
        )
    ],
    cmdclass={{"build_ext": build_ext}},
)
"""


def _get_binary_path(module_dir: Path, module_name: str) -> Path:
    """The built extension, named by setuptools for this interpreter's ABI"""
    return module_dir / f"{module_name}{sysconfig.get_config_var('EXT_SUFFIX')}"


def _get_checksum_path(module_dir: Path, module_name: str) -> Path:
    """
    The hash of the source the binary was built from. Named after the binary, so each ABI (e.g. 3.14 and 3.14t,
    which share the module dir and its source) has its own and can't vouch for another's binary
    """
    return _get_binary_path(module_dir, module_name).with_suffix(".checksum")


def _read_checksum(module_dir: Path, module_name: str) -> str | None:
    # reading a file rather than loading the module (which would need a subprocess, since a loaded
    # extension module can't be unloaded or reloaded) keeps the up-to-date check cheap
    try:
        return _get_checksum_path(module_dir, module_name).read_text(encoding="utf-8").strip()
    except FileNotFoundError:
        return None


def _load_module(name: str, path: Path) -> ModuleType:
    """Load an extension module by path, so the extmodule root needn't be on sys.path"""
    # bypassing the import system also bypasses its per-module locks, so without this two free-threaded threads
    # could both miss in sys.modules and both load the extension
    with _load_lock:
        if module := sys.modules.get(name):
            # a loaded extension module can't be reloaded, even after a rebuild
            return module
        spec = importlib.util.spec_from_file_location(name, path)
        if spec is None or spec.loader is None:  # pragma: no cover
            # defensive: a path with an extension module suffix always gets an ExtensionFileLoader
            raise ImportError(f"cannot load extension module {name} from {path}")
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
        return module


def _parse_macros(macro_list: list[str]) -> dict[str, str | None]:
    """Map ["DEF1", "DEF2=3"] to {"DEF1": None, "DEF2": "3"}"""
    return (
        Itr(macro_list)
        .map(lambda d: d.split("="))
        .map(lambda kv: (kv[0], kv[1] if len(kv) == 2 else None))
        .collect(dict)
    )


def _is_current(module_dir: Path, module_name: str, hashval: str) -> bool:
    """A built module exists and its checksum matches the hash of the source"""
    module_checksum = (
        _read_checksum(module_dir, module_name) if _get_binary_path(module_dir, module_name).exists() else None
    )
    if not module_checksum:
        logger(f"module {module_name}_ext.{module_name} not found")
        return False
    if module_checksum != hashval:
        logger(f"module is outdated ({hashval})")
        return False
    logger(f"module is up-to-date ({hashval})")
    return True


def _failure_message(qualified_name: str, module_dir: Path, log: str, diagnostics: list[CppDiagnostic]) -> str:
    """
    The first compiler error, as later ones are often knock-on effects of it, and a count of the rest. Falls back to
    the end of the log when no error could be parsed (e.g. a linker or setuptools failure)
    """
    log_path = module_dir / "build.log"
    errors = [d for d in diagnostics if d.is_error]
    if not errors:
        tail = log.splitlines()[-_LOG_TAIL_LINES:]
        return f"building {qualified_name} failed, see {log_path}:\n" + "\n".join(tail)
    n_errors, n_warnings = len(errors) - 1, len(diagnostics) - len(errors)
    rest = [f"{n_errors} more error{'s' if n_errors > 1 else ''}"] if n_errors else []
    rest += [f"{n_warnings} warning{'s' if n_warnings > 1 else ''}"] if n_warnings else []
    return (
        f"building {qualified_name} failed (line numbers refer to {module_dir / 'module.cpp'}):\n"
        f"{brief(errors[0])}\n"
        f"({', '.join([*rest, f'full log: {log_path}'])})"
    )


def _user_warnings(diagnostics: list[CppDiagnostic], module_dir: Path, include_paths: list[str]) -> list[CppDiagnostic]:
    """
    The warnings in code the user can change: module.cpp, and their own headers (under their extra include paths).
    Warnings in the standard library's, Python's, pybind11's and numpy's headers are left in build.log: e.g. pyconfig.h
    redefines _POSIX_C_SOURCE whenever a standard header comes first, and gcc reports false -Wmaybe-uninitialized
    positives inside <functional>. An allowlist, as those headers' locations vary by platform and toolchain.
    Duplicates are dropped: a compiler can report the same warning more than once, e.g. once per architecture in a
    universal2 build
    """
    # relative include paths resolve against the module dir, which is the build's cwd
    roots = [module_dir.resolve(), *((module_dir / p).resolve() for p in include_paths)]
    user_warnings = {
        (d.file, d.line, d.column, d.message): d
        for d in diagnostics
        if not d.is_error and any((module_dir / d.file).resolve().is_relative_to(root) for root in roots)
    }
    # dicts keep the first insertion's position, so the compiler's order is kept
    return list(user_warnings.values())


def _warn(qualified_name: str, diagnostics: list[CppDiagnostic]) -> None:
    """
    One CppWarning per compiler warning. The fixed message prefix lets a -W/PYTHONWARNINGS filter match it, as those
    can't import xenoform to resolve the category. Attributed to the first frame outside xenoform: the call that
    triggered the build
    """
    for d in diagnostics:
        warnings.warn(
            CppWarning(f"compiler warning in module {qualified_name!r}:\n{brief(d)}", d),
            skip_file_prefixes=(str(Path(__file__).parent),),
        )


def _build(module_dir: Path, module_name: str, module_spec: ModuleSpec, code: str, hashval: str) -> list[CppDiagnostic]:
    """Build the module, returning the warnings to issue"""
    ext_name = module_name + "_ext"
    qualified_name = f"{ext_name}.{module_name}"
    logger(f"(re)building module {qualified_name}")

    # invalidate first, so a checksum only ever exists for a completed build
    checksum_path = _get_checksum_path(module_dir, module_name)
    checksum_path.unlink(missing_ok=True)

    # save the code with the hash embedded, formatted only now so an up-to-date check runs no subprocesses
    with (module_dir / "module.cpp").open("w") as fd:
        # can't use format as its full of { }
        fd.write(format_cpp(code.replace("__HASH__", hashval)))

    logger(f"wrote {module_dir}/module.cpp")

    # everything in setup.py is either in the hashed source's header comment or comes from the interpreter, so it
    # needn't enter the checksum
    setup_py = _SETUP_PY.format(
        ext_name=ext_name,
        module_name=module_name,
        define_macros=list(_parse_macros(deduplicate(module_spec.define_macros)).items()),
        extra_compile_args=deduplicate(module_spec.extra_compile_args),
        extra_link_args=deduplicate(module_spec.extra_link_args),
        include_dirs=[np.get_include(), *deduplicate(module_spec.include_paths)],
        cxx_std=module_spec.cxx_std,
    )
    (module_dir / "setup.py").write_text(setup_py, encoding="utf-8")

    logger(f"building {qualified_name}...")
    log_path = module_dir / "build.log"
    # a subprocess, as an in-process setup() needs a chdir and stdout redirection that affect every thread, and the
    # compiler's stderr only reaches the log via the fd. The cwd is the module dir, so that relative paths in the
    # user's include and link args resolve as they always have. -P keeps the module dir off sys.path, where a built
    # module named e.g. json would shadow the stdlib
    timeout = get_config().build_timeout
    try:
        with log_path.open("wb") as log:
            result = subprocess.run(
                [sys.executable, "-P", "setup.py", "build_ext", "--inplace"],
                cwd=module_dir,
                stdout=log,
                stderr=subprocess.STDOUT,
                check=False,
                timeout=timeout,
            )
    except subprocess.TimeoutExpired as e:
        # a CompilationError, so code handling failed builds handles this too. The checksum was deleted above, so the
        # next call retries
        raise CompilationError(
            f"building {qualified_name} timed out after {timeout}s. If the build is just slow, raise "
            f"XENOFORM_BUILD_TIMEOUT. Output so far: {log_path}"
        ) from e
    if result.returncode:
        # MSVC writes in the console's code page, so the log may not be valid UTF-8
        log = log_path.read_text(encoding="utf-8", errors="replace")
        diagnostics = parse_diagnostics(log)
        raise CompilationError(_failure_message(qualified_name, module_dir, log, diagnostics), diagnostics)
    checksum_path.write_text(hashval, encoding="utf-8")
    logger(f"built {qualified_name}")
    diagnostics = parse_diagnostics(log_path.read_text(encoding="utf-8", errors="replace"))
    return _user_warnings(diagnostics, module_dir, deduplicate(module_spec.include_paths))


def _check_build_fetch_module_impl(
    module_name: str,
    module_spec: ModuleSpec,
) -> ModuleType:
    module_dir = get_config().extmodule_root / f"{module_name}_ext"

    code, hashval = module_spec.make_source(module_name)

    # the up-to-date path takes no lock, so it creates no files. A torn checksum read while another process writes it
    # can't match a full hash, so the worst case is taking the lock below and checking again
    built_warnings: list[CppDiagnostic] = []
    if not _is_current(module_dir, module_name, hashval):
        module_dir.mkdir(exist_ok=True, parents=True)
        # filelock is thread-local by default, so this serialises threads as well as processes
        with FileLock(module_dir / ".build.lock"):
            # whoever held the lock may just have built this same source
            if not _is_current(module_dir, module_name, hashval):
                built_warnings = _build(module_dir, module_name, module_spec, code, hashval)
    # outside the lock, and after the checksum is written: a filter can turn a warning into an exception, but the
    # build still succeeded. Only a build warns, so an up-to-date module doesn't repeat them
    _warn(f"{module_name}_ext.{module_name}", built_warnings)
    return _load_module(f"{module_name}_ext.{module_name}", _get_binary_path(module_dir, module_name))


@lru_cache(maxsize=256)
def _get_module(module_name: str) -> ModuleType:
    module = _check_build_fetch_module_impl(module_name, _module_registry[module_name])
    logger(f"imported compiled module {module.__name__}")
    return module


def _translate_constants(entries: list[str], frame: FrameType) -> tuple[list[str], list[str]]:
    """
    Look up each constant by name where the decorator is written (locals, e.g. a function or class body, shadowing
    globals, which include imported names), and render it as a C++ declaration. Values are captured now
    """
    scope = ChainMap(frame.f_locals, frame.f_globals)
    declarations, headers = [], []
    for entry in entries:
        name, cpp_type = parse_constant(entry)
        if name not in scope:
            raise ValueError(f"constant {name!r} not found where @compile is used")
        declaration, constant_headers = translate_constant(name, scope[name], cpp_type)
        declarations.append(declaration)
        headers += constant_headers
    return declarations, headers


def _check_annotations[**P, R](func: Callable[P, R]) -> None:
    """Ensures all args and return are typed"""
    sig = inspect.signature(func)

    missing_annotations = ", ".join(
        param for param, type_ in sig.parameters.items() if type_.annotation is inspect.Parameter.empty
    )
    if sig.return_annotation is inspect.Parameter.empty:
        missing_annotations += ", (return)"

    if missing_annotations:
        raise AnnotationError(f"Function {func.__name__} has missing annotations: {missing_annotations}")  # ty: ignore[unresolved-attribute]


@lru_cache(maxsize=256)
def _get_function(module_name: str, function_name: str) -> Callable[..., Any]:
    module = _get_module(module_name)
    logger(f"redirected {module_name}.{function_name[1:]} to compiled function {module.__name__}.{function_name}")
    return getattr(module, function_name)


def compile[**P, R](
    *,
    vectorise: bool = False,
    define_macros: list[str] | None = None,
    extra_includes: list[str] | None = None,
    extra_include_paths: list[str] | None = None,
    extra_compile_args: list[str] | None = None,
    extra_link_args: list[str] | None = None,
    return_value_policy: ReturnValuePolicy = ReturnValuePolicy.Automatic,
    cxx_std: int = 20,
    help: str | None = None,
    module_name: str | None = None,
    constants: list[str] | None = None,
) -> Callable[[Callable[P, R]], Callable[P, R]]:
    """
    Decorator factory for compiling C/C++ function implementations into extension modules.

    Parameters:
        vectorise (bool, optional): If True, vectorizes the compiled function for array operations.
        define_macros: list[str] | None = None,
        extra_includes (list[str], optional): Additional header/inline files to include during compilation.
        extra_include_paths (list[str], optional): Additional paths search for headers.
        extra_compile_args (list[str], optional): Extra arguments to pass to the compiler.
        extra_link_args (list[str], optional): Extra arguments to pass to the linker.
        cxx_std (int, optional, default 20): C++ standard to compile
        help (str, optional): Docstring for the function
        module_name (str, optional): Name of the extension module to build the function into, defaulting to the
            stem of the file defining the function. Functions from different files sharing a name share a module.
            Set it in notebooks, where the default (a hash of the cell's source) changes with every edit.
        constants (list[str], optional): Python variables to declare as C++ constants in the module, by name:
            "NAME", or "NAME: cpp_type" to override the type. Looked up where the decorator is written.

    Returns:
        Callable[..., Callable[..., Any]]: A function that when called, will return the compiled function.

    Debug logging is controlled globally by the presence of the `XENOFORM_VERBOSE` environment
    variable (any value enables it), not per-decorator.
    """
    # non-ASCII identifiers are valid python, but CPython looks for a punycoded PyInitU_ symbol for them,
    # which pybind11 doesn't generate
    if module_name is not None and not (
        module_name.isascii() and module_name.isidentifier() and not keyword.iskeyword(module_name)
    ):
        raise ValueError(f"module_name {module_name!r} must be an ASCII python identifier and not a keyword")

    # the caller's frame is the scope the decorator is written in. It's only read here, never stored
    constant_defs, constant_headers = _translate_constants(constants, sys._getframe(1)) if constants else ([], [])

    def register_function[**P, R](func: Callable[P, R]) -> Callable[P, R]:
        """This registers the function, actual compilation is deferred"""
        extmodule_root = get_config().extmodule_root

        scope = get_function_scope(func)

        _check_annotations(func)

        sig, args, headers = translate_function_signature(func)
        target_module = module_name or Path(inspect.getfile(func)).stem
        function_body = sig + " {" + (func.__doc__ or "") + "}"

        logger(f"registering {target_module}_ext.{target_module}.{func.__name__} (in {extmodule_root})")  # ty: ignore[unresolved-attribute]

        if vectorise:
            function_body = f"py::vectorize({function_body})"
            headers.append("<pybind11/numpy.h>")

        arg_defs = "".join(f", {kwarg}" for kwarg in args)

        # need to directly alter the original function's help...
        # for reasons unknown, copying the pybind11 function's docstr to the python stub on first use
        # (in _get_function) doesn't actually work
        # TODO try this:
        # > Modifying func.__doc__ directly can be an unexpected side effect for a decorator. While functional, it
        # > deviates from the common pattern of decorators modifying the returned wrapper function's attributes. If
        # > help is provided, test_help.py's assertion should also be adjusted to == docstr for exact match.
        if help:
            func.__doc__ = help

        # ...as well as adding the help to the ext module
        function_spec = FunctionSpec(
            name=func.__name__,  # ty: ignore[unresolved-attribute]
            body=function_body,
            arg_annotations=arg_defs,
            scope=scope,
            return_value_policy=return_value_policy,
            help=help,
        )

        _module_registry[target_module].add_function(
            function_spec,
            headers=headers + constant_headers + (extra_includes or []),
            include_paths=extra_include_paths or [],
            define_macros=define_macros or [],
            extra_compile_args=extra_compile_args or [],
            extra_link_args=extra_link_args or [],
            constants=constant_defs,
            cxx_std=cxx_std,
        )

        @wraps(func)
        def call_function(*args: P.args, **kwargs: P.kwargs) -> R:
            """Compilation is deferred until here (and cached)"""
            cpp_fn = cast(Callable[P, R], _get_function(target_module, function_spec.qualified_cpp_name()))
            return cpp_fn(*args, **kwargs)

        return call_function

    return register_function
